def tw(family, s):
    """回傳日文 s 的繁體中文版 (字串, 覆寫參數)。不含日文的文字原樣回傳"""
    if not any("　" <= ch <= "鿿" or "＀" <= ch <= "￯" for ch in s):
        return s, {}
    v = TW.get(s)
    if v is None:
        raise KeyError(f"labels_tw.py 中沒有中文：{s!r}")
    t, o = (v, {}) if isinstance(v, str) else (v["t"], {k: v[k] for k in ("size", "dx", "dy", "anchor") if k in v})
    return t.replace("&", "&amp;").replace("<", "&lt;"), o
